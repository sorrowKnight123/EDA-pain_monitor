/**
  ******************************************************************************
  * @file    bsp_iwdg.c
  * @brief   独立看门狗：寄存器级启动与喂狗（不引入 HAL IWDG 驱动）
  ******************************************************************************
  */
#include "bsp_iwdg.h"

/* 独立看门狗（寄存器级配置，不引入 HAL IWDG 驱动，看门狗尽量独立）：
 * 启动 LSI(40kHz)，预分频 /64，重载 625 → 约 1s 超时。
 * 主循环或任何 late-stage 卡死（含 Error_Handler 挂起）超过 1s 自动复位恢复 */
void bsp_iwdg_init(void)
{
  /* 有界等待 LSI 就绪：本函数在 lcd_ready 置位之后、看门狗启动之前被调用，
   * 此刻屏上已是正常界面。LSI 不起振时若在此死等，设备就永久停在"看着正常、
   * 不出数据"的状态；此处也没有任何错误路径可走 —— 狗还没启动，调 Error_Handler
   * 只会变成一块红屏 + 永久挂起，所以超时后继续往下走（写入无效的 IWDG 配置无害） */
  SET_BIT(RCC->CSR, RCC_CSR_LSION);              /* 启动 LSI */
  for (uint32_t t = 0; (READ_BIT(RCC->CSR, RCC_CSR_LSIRDY) == RESET) && (t < 200000u); t++) { }

  IWDG->KR  = 0x5555;                            /* 解锁 PR/RLR */
  IWDG->PR  = 2;                                 /* 预分频 /64 → 625Hz 计数 */
  IWDG->RLR = 625;                               /* 625 计数 ≈ 1.0s */
  IWDG->KR  = 0xAAAA;                            /* 重载计数 */
  IWDG->KR  = 0xCCCC;                            /* 启动看门狗（此后不可关闭） */
}

/* 主循环每轮喂狗（重载计数，防止约 1s 超时复位）。
 * 采集与上报都停着时主循环仍在跑，所以它们各自的停摆要靠自己的监测兜住，不指望看门狗 */
void bsp_iwdg_feed(void)
{
  IWDG->KR = 0xAAAA;
}